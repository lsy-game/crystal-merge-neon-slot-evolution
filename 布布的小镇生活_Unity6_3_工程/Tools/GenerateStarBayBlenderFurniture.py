def unity_loc(value):
    return (value[0], value[2], value[1])


def unity_scale(value):
    return (value[0], value[2], value[1])


def clear_scene():
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete()


def mat(name, color, roughness=0.55, metallic=0.0, alpha=None):
    material = bpy.data.materials.new(name)
    material.use_nodes = True
    bsdf = material.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = color
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    if alpha is not None:
        material.blend_method = "BLEND"
        material.use_screen_refraction = True
        bsdf.inputs["Alpha"].default_value = alpha
    return material


def cube(name, loc, scale, material, bevel=0.03):
    bpy.ops.mesh.primitive_cube_add(size=1, location=unity_loc(loc))
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = unity_scale(scale)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if material:
        obj.data.materials.append(material)
    if bevel > 0:
        mod = obj.modifiers.new("圆角倒角", "BEVEL")
        mod.width = bevel
        mod.segments = 8
        obj.modifiers.new("柔和法线", "WEIGHTED_NORMAL")
    return obj


def cylinder(name, loc, radius, depth, material, vertices=32, bevel=0.0):
    bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=depth, location=unity_loc(loc))
    obj = bpy.context.object
    obj.name = name
    if material:
        obj.data.materials.append(material)
    if bevel > 0:
        mod = obj.modifiers.new("边缘圆润", "BEVEL")
        mod.width = bevel
        mod.segments = 6
        obj.modifiers.new("柔和法线", "WEIGHTED_NORMAL")
    return obj


def sphere(name, loc, scale, material):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=32, ring_count=16, radius=0.5, location=unity_loc(loc))
    obj = bpy.context.object
    obj.name = name
    obj.scale = unity_scale(scale)
    if material:
        obj.data.materials.append(material)
    obj.modifiers.new("柔和法线", "WEIGHTED_NORMAL")
    return obj


def torus(name, loc, major, minor, material):
    bpy.ops.mesh.primitive_torus_add(major_radius=major, minor_radius=minor, major_segments=48, minor_segments=10, location=unity_loc(loc))
    obj = bpy.context.object
    obj.name = name
    if material:
        obj.data.materials.append(material)
    return obj


def rotate(obj, degrees, axis="Z"):
    if axis == "X":
        obj.rotation_euler[0] = math.radians(degrees)
    elif axis == "Y":
        obj.rotation_euler[1] = math.radians(degrees)
    else:
        obj.rotation_euler[2] = math.radians(degrees)
    return obj


def export_model(filename):
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    path = os.path.join(OUTPUT_DIR, filename)
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.export_scene.fbx(
        filepath=path,
        use_selection=True,
        apply_unit_scale=True,
        bake_space_transform=False,
        object_types={"MESH"},
        add_leaf_bones=False,
        mesh_smooth_type="FACE",
        use_mesh_modifiers=True,
    )
    return path


